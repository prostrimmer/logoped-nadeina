// Функция обработки клика по карточке мальчика (выделение/снятие выбора)
function toggleL27T4(cardElement) {
    // Переключаем класс 'selected' (добавляем, если его не было, или удаляем, если он уже есть)
    cardElement.classList.toggle('selected');
    // При каждом новом клике убираем старые результаты проверки (зеленый/красный контур), если они были
    cardElement.classList.remove('correct', 'wrong');
}

// Функция проверки правильности выбранных близнецов
function checkL27Task4() {
    // Находим все карточки четвертого задания
    const cards = document.querySelectorAll('.l27-t4-card');
    // Находим блок для вывода итогового текста результата
    const resArea = document.getElementById('res-27-4');
    
    // Переменная для подсчета общего количества выбранных пользователем карточек
    let selectedCount = 0;
    // Переменная для подсчета количества правильно выбранных близнецов
    let correctSelectedCount = 0;
    // Общий флаг успешности прохождения задания
    let isAllCorrect = true;

    // Запускаем цикл перебора каждой карточки в задании
    cards.forEach(card => {
        // Проверяем, является ли эта карточка задуманным правильным ответом (data-correct="true")
        const shouldBeSelected = card.dataset.correct === "true";
        // Проверяем, выбрал ли ее пользователь (есть ли класс 'selected')
        const isSelected = card.classList.contains('selected');

        // Если карточка выбрана пользователем
        if (isSelected) {
            selectedCount++; // Увеличиваем счетчик выбранных карточек на 1
            
            // Если карточка действительно должна была быть выбрана
            if (shouldBeSelected) {
                card.classList.add('correct');    // Подсвечиваем её зеленым контуром (правильно)
                correctSelectedCount++;           // Увеличиваем счетчик верных попаданий
            } else {
                card.classList.add('wrong');      // Подсвечиваем её красным контуром (ошибка — лишний выбор)
                isAllCorrect = false;             // Меняем флаг успеха на false
            }
        } else {
            // Если карточка НЕ выбрана пользователем, но при этом она должна была быть правильным ответом
            if (shouldBeSelected) {
                isAllCorrect = false;             // Ребенок пропустил одного из близнецов, фиксируем ошибку
            }
        }
    });

    // Дополнительная проверка: ребенок должен выбрать ровно 2 карточки
    if (selectedCount !== 2) {
        isAllCorrect = false;                     // Если выбрано больше или меньше двух — задание не засчитывается
    }

    // Анализируем результаты и выводим соответствующее сообщение в блок результатов
    if (isAllCorrect && correctSelectedCount === 2) {
        resArea.innerHTML = "<b>Отлично! Ты безупречно нашел двух одинаковых мальчиков-близнецов!</b>";
        resArea.style.color = "#27ae60";          // Окрашиваем текст в зеленый цвет при победе
    } else {
        resArea.innerHTML = "<b>Не совсем так. Внимательно посмотри на узоры на кепках и найди двух абсолютно одинаковых мальчиков!</b>";
        resArea.style.color = "#e67e22";          // Окрашиваем текст в оранжевый цвет при ошибке
    }
}

